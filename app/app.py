import streamlit as st
import pandas as pd
import joblib
from pathlib import Path


# --------------------------------------------------
# Page configuration
# --------------------------------------------------

st.set_page_config(
    page_title="Sydney Housing Price Prediction",
    page_icon="🏠",
    layout="centered"
)


# --------------------------------------------------
# Load trained model
# --------------------------------------------------

BASE_DIR = Path(__file__).resolve().parent.parent
MODEL_PATH = BASE_DIR / "models" / "final_gradient_boosting_model.pkl"

model = joblib.load(MODEL_PATH)


# --------------------------------------------------
# Title and introduction
# --------------------------------------------------

st.title("🏠 Sydney Housing Price Prediction")
st.subheader("Machine Learning Decision Support System")

st.write(
    """
    Enter the characteristics of a Sydney property below to receive
    an estimated sale price from the trained Gradient Boosting regression model.
    """
)

st.info(
    "The prediction is an estimate based on the patterns learned from "
    "the project's 100-property dataset. It should be used as a "
    "decision-support estimate rather than a professional property valuation."
)


# --------------------------------------------------
# Property information
# --------------------------------------------------

st.header("Property Details")

suburb = st.selectbox(
    "Suburb",
    ["Manly", "Parramatta", "Liverpool"]
)

property_type = st.selectbox(
    "Property Type",
    ["Apartment", "Unit", "House", "Townhouse", "Studio"]
)

bedrooms = st.number_input(
    "Bedrooms",
    min_value=1,
    max_value=10,
    value=2,
    step=1
)

bathrooms = st.number_input(
    "Bathrooms",
    min_value=1,
    max_value=10,
    value=1,
    step=1
)

parking = st.number_input(
    "Parking Spaces",
    min_value=0,
    max_value=10,
    value=1,
    step=1
)

area_available = st.checkbox(
    "Listed area information is available",
    value=True
)

if area_available:
    listed_area_m2 = st.number_input(
        "Listed Area (m²)",
        min_value=1.0,
        max_value=2000.0,
        value=100.0,
        step=1.0
    )
else:
    listed_area_m2 = None
    st.caption(
        "No area information will be provided. "
        "The model will handle the missing value using its preprocessing pipeline."
    )


# --------------------------------------------------
# Sale date information
# --------------------------------------------------

st.header("Sale Information")

sale_year = st.number_input(
    "Sale Year",
    min_value=2025,
    max_value=2030,
    value=2026,
    step=1
)

sale_month = st.number_input(
    "Sale Month",
    min_value=1,
    max_value=12,
    value=9,
    step=1
)

sale_quarter = ((sale_month - 1) // 3) + 1


# --------------------------------------------------
# Prediction
# --------------------------------------------------

if st.button("🔮 Predict Sale Price", use_container_width=True):

    input_data = pd.DataFrame({
        "suburb": [suburb],
        "property_type": [property_type],
        "bedrooms": [bedrooms],
        "bathrooms": [bathrooms],
        "parking": [parking],
        "listed_area_m2": [listed_area_m2],
        "sale_year": [sale_year],
        "sale_month": [sale_month],
        "sale_quarter": [sale_quarter],
        "area_available": [int(area_available)]
    })

    prediction = model.predict(input_data)[0]

    st.success(
        f"### Estimated Sale Price: AUD ${prediction:,.0f}"
    )

    st.caption(
        "This prediction is generated by the project's trained "
        "Gradient Boosting regression pipeline."
    )